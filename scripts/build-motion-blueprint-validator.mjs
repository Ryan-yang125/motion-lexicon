/* global console, process */

import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "..");
const entryPoint = path.join(scriptDirectory, "validate-motion-blueprint-source.mjs");
const outputPath = path.join(repositoryRoot, "skills", "motion-lexicon", "scripts", "validate-motion-blueprint.mjs");
const checkOnly = process.argv.includes("--check");
const banner = "/* Generated by scripts/build-motion-blueprint-validator.mjs. Edit scripts/validate-motion-blueprint-source.mjs, then rebuild. Third-party notices: skills/motion-lexicon/THIRD_PARTY_NOTICES.md. */";

const result = await build({
  entryPoints: [entryPoint],
  bundle: true,
  format: "esm",
  legalComments: "inline",
  platform: "node",
  target: "node20",
  write: false,
  banner: { js: banner }
});

const bundledValidator = result.outputFiles[0]?.text;
if (!bundledValidator) {
  throw new Error("Motion Blueprint validator bundle was not produced.");
}

if (checkOnly) {
  const currentValidator = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (currentValidator !== bundledValidator) {
    console.error("Motion Blueprint validator bundle is stale. Run npm run skill:bundle.");
    process.exitCode = 1;
  } else {
    console.log("Motion Blueprint validator bundle is current.");
  }
} else {
  fs.writeFileSync(outputPath, bundledValidator);
  console.log(`Motion Blueprint validator bundle written: ${path.relative(repositoryRoot, outputPath)}`);
}
